"""Verilator build of the leakage testbench.

The toggle model must be the one of the Icarus VPI module, register for
register. The register list is therefore taken from that module ($tg_names
in a one-execution Icarus run) and turned into tg_regs.vh, a concatenation
of the same registers by hierarchical reference; tb_leak.v, compiled with
TG_VERILOG, counts the bits of it that change at each edge. cross_check()
compares the traces of both simulators bit for bit.
"""
import hashlib
import os
import shutil
import subprocess

import numpy as np

from common import BUILD, CONFIGS, HERE, RTL, compile_cfg, make_inputs, run_vvp, write_inputs

VERILATOR = (os.environ.get("VERILATOR") or shutil.which("verilator")
             or os.path.join(os.path.dirname(os.path.dirname(HERE)),
                             "tools", "oss-cad-suite", "bin", "verilator"))


def register_list(cfg):
    """Registers collected by the VPI module for this configuration."""
    image = compile_cfg(cfg)
    d = os.path.join(BUILD, "names_%s" % cfg)
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    flags, s0, s1, _ = make_inputs(cfg, 1, 1)
    write_inputs(os.path.join(d, "in.hex"), flags, s0, s1)
    extra = ["+delta=1"] if cfg == "staggered" else []
    run_vvp(image, ["+in=in.hex", "+n=1", "+dump=dump.bin", "+names=names.txt"] + extra, d)
    regs = []
    for line in open(os.path.join(d, "names.txt")):
        _, width, _, name = line.split()
        regs.append((name, int(width)))
    shutil.rmtree(d)
    return regs


def _sources(cfg):
    folder, _, _ = CONFIGS[cfg]
    src_dir = os.path.join(RTL, folder)
    return [os.path.join(HERE, "tb_leak.v"), os.path.join(HERE, "verilator.py"),
            os.path.join(HERE, "vpi", "toggle.c")] + sorted(
        os.path.join(src_dir, f) for f in os.listdir(src_dir)
        if f.endswith(".v") and not f.startswith("tb_") and not f.startswith("chk_"))


def build(cfg):
    """Compile the Verilator binary of one configuration, or reuse it if
    its sources and macros have not changed; returns its path."""
    folder, macros, _ = CONFIGS[cfg]
    out = os.path.join(BUILD, "vl_%s" % cfg)
    h = hashlib.sha256((VERILATOR + "|" + " ".join(macros)).encode())
    for f in _sources(cfg):
        h.update(open(f, "rb").read())
    stamp = h.hexdigest()
    exe = os.path.join(out, "obj", "sim")
    if os.path.exists(exe) and os.path.exists(os.path.join(out, "stamp")) and \
            open(os.path.join(out, "stamp")).read() == stamp:
        return exe
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(out)
    regs = register_list(cfg)
    width = sum(w for _, w in regs)
    refs = [n[len("tb_leak."):] for n, _ in regs]
    with open(os.path.join(out, "tg_regs.vh"), "w") as fh:
        fh.write("// generated by leakage/verilator.py from the VPI register list\n")
        fh.write("localparam TG_W = %d;\n" % width)
        fh.write("wire [TG_W-1:0] tg_cur = {\n    " + ",\n    ".join(refs) + "\n};\n")
    src_dir = os.path.join(RTL, folder)
    srcs = sorted(os.path.join(src_dir, f) for f in os.listdir(src_dir)
                  if f.endswith(".v") and not f.startswith("tb_") and not f.startswith("chk_"))
    cmd = [VERILATOR, "--binary", "--timing", "-O3", "-Wno-fatal", "-Wno-lint",
           "-Wno-style", "--x-assign", "0", "--x-initial", "0",
           "--top-module", "tb_leak", "-I" + out, "--Mdir", os.path.join(out, "obj"),
           "-o", "sim"] + ["-D" + m for m in macros + ["NO_VPI", "TG_VERILOG"]] + \
          [os.path.join(HERE, "tb_leak.v")] + srcs
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode or not os.path.exists(exe):
        raise RuntimeError("verilator build failed:\n" + r.stdout[-3000:] + r.stderr[-3000:])
    with open(os.path.join(out, "stamp"), "w") as fh:
        fh.write(stamp)
    return exe


def run(exe, args, cwd):
    r = subprocess.run([exe] + args, cwd=cwd, capture_output=True, text=True)
    if "[DONE]" not in r.stdout:
        raise RuntimeError("simulation failed:\n" + r.stdout[-3000:] + r.stderr[-3000:])
    return r.stdout


def cross_check(cfg, n=20, delta=9, seed=99):
    """Same inputs on Icarus (VPI) and Verilator: traces and read-backs must
    be identical. Returns (identical traces, identical read-backs, shape)."""
    d = os.path.join(BUILD, "xcheck_%s" % cfg)
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
    flags, s0, s1, _ = make_inputs(cfg, n, seed)
    write_inputs(os.path.join(d, "in.hex"), flags, s0, s1)
    extra = ["+delta=%d" % delta] if cfg == "staggered" else []
    run_vvp(compile_cfg(cfg), ["+in=in.hex", "+n=%d" % n, "+out=ic.bin", "+chk=ic.hex"] + extra, d)
    run(build(cfg), ["+in=in.hex", "+n=%d" % n, "+out=vl.bin", "+chk=vl.hex"] + extra, d)
    a = np.fromfile(os.path.join(d, "ic.bin"), dtype=np.uint16)
    b = np.fromfile(os.path.join(d, "vl.bin"), dtype=np.uint16)
    same_rb = open(os.path.join(d, "ic.hex")).read() == open(os.path.join(d, "vl.hex")).read()
    return a.shape == b.shape and np.array_equal(a, b), same_rb, (a.shape, b.shape), d
